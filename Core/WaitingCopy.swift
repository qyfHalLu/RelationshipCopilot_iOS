//
// 「等对方写」那一行该说什么。
//
// ## 为什么这几句话值得单独一个文件 + 单独测
//
// 服务端用 Cloudflare KV，**最终一致，读写之间最长约 60 秒延迟**。
// 也就是说，"我们没查到" 和 "对方没写" 是两件不同的事，
// 但它们在界面上长得一模一样 —— 都表现为 `testimonies["b"] == nil`。
//
// 如果文案写成「TA 还没提交」，界面就在陈述一件我们并不知道的事。
// 后果不是技术错误，是**人际误解**：用户会把一次同步延迟读成
// "TA 是不是不想写 / 在敷衍我"。这个 App 处理的正是这种时刻，
// 一句不该说的话会放大焦虑，而它本来可以完全避免。
//
// 所以规则是：**只说我们观察到的，不说对方做了什么。**
//   · 观察到 → "还没收到 TA 那一份"     （可以说，这是事实）
//   · 未观察 → "TA 还没提交"            （不能说，这是推测）
//
// 抽成纯函数是为了能自动化验证：这几句话的差别靠读代码看不出来，
// 但一旦有个断言把"不许出现『还没提交』"钉死，以后就不会再被改回去。
//

import Foundation

/// 「TA 写完了」这一行右边那句说明。
enum WaitingCopy {

    /// 已连续查到"对方那份还不在"的次数。
    ///
    /// **只统计"请求成功、但对方那份还没到"**。以下两种情况不计数：
    ///   · 请求本身失败（网络错误）—— 那种情况我们根本不知道对方写没写
    ///   · 对方那份已经取到了 —— 那时显示的是"可以看结果了"，与计数无关
    ///
    /// 这个定义很重要：次数被用来决定"要不要解释同步延迟"，
    /// 而用错误的次数去解释等于编造信息。
    static func counterpartDetail(hasWritten: Bool, missCount: Int) -> String {
        if hasWritten { return "可以看结果了" }

        // 第一次查不到时不解释延迟 —— 用户刚建完链接就点刷新，
        // 那时对方大概率是真的还没开始写，讲同步延迟只会让人困惑。
        //
        // 连续两次以上查不到才补一句，因为这时"延迟"才是一个合理的可能。
        if missCount >= 2 {
            return "还没收到。刚提交的话，可能要等半分钟才同步过来"
        }
        return "还没收到 TA 那一份"
    }

    // MARK: - 「TA 打开了链接」这一行
    //
    // 同一个坑的第三处。`InviteStatus.counterpartOpenedLink` 来自服务端
    // `slots.b`；当 `status == nil`（还没查过 / 查询失败）时**根本没有这个值**，
    // 但视图原先写的是 `status?.counterpartOpenedLink == true ? "已经打开过了" : "还没有打开"`
    // —— 把"没有值"和"值是 false"合并成了同一句「还没有打开」。
    //
    // 截图抓到的实际画面：顶部红条写着「连不上服务端」，
    // 紧接着下面却笃定地说「TA 打开了链接 / 还没有打开」。
    // 连不上服务端时，我们**不可能**知道对方有没有点开。
    // 这和「TA 还没提交」是同一类错误：把不知道说成知道。

    /// 「TA 打开了链接」这一行的说明文字。
    ///
    /// - Parameter opened: `nil` 表示状态未知（还没查到或查询失败）。
    static func openedLinkDetail(opened: Bool?) -> String {
        guard let opened else { return "暂时查不到" }
        return opened ? "已经打开过了" : "还没有打开"
    }

    /// 「TA 打开了链接」这一行的圆点是否画成"进行中"。
    ///
    /// 未知时**不画进行中**：进行中是一种断言，而我们什么都不知道。
    static func openedLinkIsInProgress(opened: Bool?) -> Bool {
        opened == false
    }
}
